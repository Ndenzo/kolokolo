                              <p class="col-lg-4" style="font-size: 10px; text-align: justify;">
                                   <strong>Alors j’ai dit: voici, je viens pour faire, ô Dieu, ta volonté » hebreux 10,7</strong>

                                   <br>
                                   Pharmacien de formation, musicien par passion et biologiste en devenir, Guy Armand Koffi est un jeune Artiste Chrétien ivoirien résidant au Sénégal depuis plus d’une dizaine d’années.
                                   Issu d’une fratrie de 7 enfants dont 3 filles, Armand occupe la 4è position. Ce qui lui confère un certain confort pour parler aux plus grands comme aux plus jeunes que lui.
                                   Après son Certificat d’Études Primaires en 2002, Armand rejoint le petit Séminaire de Bingerville puis celui d’Aboisso (Côte d’Ivoire) en fin de cycle...
                                   Dès la 6è, il s’intéresse à la musique et se fait initier au solfège et à quelques instruments. Le talent musical qui sommeillait en lui, va très vite s’aiguiser au fil des années.
                                   A  12 ans, il avait déjà du cran pour officier comme maître de chœur d’une chorale d’Adultes. Très jeune, Armand Koffi avait déjà acquis un brevet de respectabilité pour ses talents artistico-musicaux. Initié très tôt à la musique, c’est à partir de la 2nde (moyen séminaire de Yopougon), qu’il va passer à la vitesse supérieure. Le maniement d’ instruments tels que le piano, la guitare basse, ne lui est pas totalement étranger, même s’il ne les pratique pas. Il a préféré s’investir à fond  dans les harmonies.
                              </p>
                              <p class="col-lg-4" style="font-size: 10px; text-align: justify;">
                                   Fervent catholique et séminariste, il composait ses premiers airs musicaux sous la supervision des certains prêtres ivoiriens (figures de proue de la musique chrétienne ivoirienne). L’inspiration fructueuse, toutes les circonstances de la vie sont bonnes pour traduire sa reconnaissance à Dieu à travers un chant.
                                   Aujourd’hui, il s’est donné pour mission de soigner les corps par le médicament, mais aussi les cœurs par le chant sacré. Artiste polyvalent, il a maintes cordes à son arc : auteur-compositeur, interprète, metteur en scène, chorégraphe, décorateur de scène, percussionniste, maître de chœur.
                                   Il fit plusieurs scènes de concert au théâtre Sorano et au grand théâtre de Dakar avec ses comédies musicales: Le Roi David, Joseph en Égypte, La reine Esther, Samson et Dalilah.
                                   Ce talent artistique, il le dédie au Père céleste.
                                   Longtemps resté dans l’ombre, il a décidé depuis deux ans de lancer sa carrière en tant que Artiste Chrétien en Novembre 2018. Après son premier single intitulé, «Amour infini» (2019), le jeune artiste a sorti «Praise» son deuxième, fin févier (2020), ainsi que son premier clip. Cependant «Alpha Omega» et «Mon berger» sont sortis simultanément en Août (2020) avec un clip aussi édifiant. Armand fait les choses et va au rythme de la providence.
                              </p>

                              <p class="col-lg-4" style="font-size: 10px; text-align: justify;">
                                   Méticuleux certes, ce docteur en pharmacie veut toujours se laisser guider volontiers par Dieu.
                                   Par ailleurs, Armand Koffi «apporte surtout de la fraicheur» dans la musique religieuse chrétienne d’Afrique. Il y puise d’ailleurs dans les profondeurs du riche patrimoine culturel du continent. Compositeur prolifique et aguerri, Armand a à son actif plus de deux cents (200) compositions, notamment des chants liturgiques depuis ces débuts à 12 ans.
                                   Ainsi, Venu apporter un souffle nouveau à la musique chrétienne Africaine, il ne compte pas s'arreter en si bon chemin et prépare actuellement  son premier album dont la sortie est prévu pour fin 2021 sous la houlette de grand musiciens tels que Alain Oyono, Romuald N'guessan, Akatche Koffi, Jean Ebo, Willy djette, Yann Bana et Francis Ayo.
                                   On pourrait definir Armand KOFFI comme un nouveau visage de la musique chretienne car il propose la recette infaillible du mixage de musique et de prière de par la profondeur de ses textes.
                              </p>
